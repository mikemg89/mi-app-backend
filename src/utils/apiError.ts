/**
 * Error con código HTTP y código de negocio estable.
 * El middleware central lo traduce a una respuesta JSON.
 */
export class ApiError extends Error {
  readonly status: number;
  readonly code: string;

  constructor(status: number, code: string, message: string) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.code = code;
  }
}
